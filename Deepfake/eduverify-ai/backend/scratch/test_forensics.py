from transformers import AutoProcessor, Qwen2VLForConditionalGeneration
from qwen_vl_utils import process_vision_info

model_id = "Qwen/Qwen2-VL-2B-Instruct"
print("Loading model...")
processor = AutoProcessor.from_pretrained(model_id)
model = Qwen2VLForConditionalGeneration.from_pretrained(
    model_id, 
    torch_dtype=torch.float16, 
    device_map="cuda"
)

def evaluate_image(image_path: str):
    img = Image.open(image_path)
    if max(img.size) > 1200:
        img.thumbnail((1200, 1200), Image.Resampling.LANCZOS)
        
    messages = [
        {
            "role": "system",
            "content": (
                "You are an expert digital forensics examiner specializing in identifying AI-generated documents, "
                "synthetic handwriting, and fake student handwritten assignments generated by models like ChatGPT DALL-E, "
                "Midjourney, and Stable Diffusion.\n"
                "Examine the handwriting strokes, glyph repetition, ink bleeding, ruled-line alignment, and sensor noise."
            )
        },
        {
            "role": "user",
            "content": [
                {"type": "image", "image": img},
                {
                    "type": "text", 
                    "text": (
                        "Examine this handwritten page carefully. Is this an authentic physical camera photograph/scan "
                        "of real human handwriting, or was this digitally generated by an AI model (like ChatGPT/DALL-E)?\n"
                        "Respond strictly in this format:\n"
                        "VERDICT: [AI_GENERATED or AUTHENTIC_PHYSICAL]\n"
                        "CONFIDENCE: [HIGH or MODERATE]\n"
                        "REASONS:\n"
                        "- [reason 1]\n"
                        "- [reason 2]"
                    )
                }
            ]
        }
    ]
    
    text = processor.apply_chat_template(messages, tokenize=False, add_generation_prompt=True)
    image_inputs, video_inputs = process_vision_info(messages)
    inputs = processor(
        text=[text],
        images=image_inputs,
        videos=video_inputs,
        padding=True,
        return_tensors="pt"
    ).to("cuda")
    
    output_ids = model.generate(**inputs, max_new_tokens=150)
    generated_ids = [out[len(inp):] for inp, out in zip(inputs.input_ids, output_ids)]
    output = processor.batch_decode(generated_ids, skip_special_tokens=True)[0]
    return output

